def _name(table: list[str], level: int | None) -> str | None:
    if not level:
        return None
    if 1 <= level <= len(table):
        return table[level - 1]
    return f"Rank {level}"


def ground_rank(level: int | None) -> str | None:
    return _name(RANKS_GROUND, level)


def air_rank(level: int | None) -> str | None:
    return _name(RANKS_AIR, level)
